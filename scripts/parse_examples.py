"""Run addresses through a tagger and the PIN check, as app/demo.py does, and save what comes out.

    uv run --extra train --extra demo python -m scripts.parse_examples indian_address_parser_test_cases.md \
        --model models/muril-synfull-s42 --run-id 20261116-muril-synfull-testcases20-s42 \
        --out-md report/test_cases_output.md

The input is either a markdown file in which each case is a `## <ID> ...` heading followed by a ```text block (the
format of indian_address_parser_test_cases.md), or a plain text file with one address per line. These addresses have
no gold tags, so nothing is scored: the output goes to results/<run-id>.outputs.jsonl and, with --out-md, to a
readable markdown file. --model takes crf, rules, a saved model folder or a Hugging Face model name.
"""
import argparse
import json
import re
from collections import Counter
from datetime import date
from pathlib import Path

from app.demo import crf_tagger, parse, rules_tagger, transformer_tagger
from src.normalize.gazetteer import Gazetteer

FIELDS = ("house", "building", "street", "landmarks", "locality", "city", "district", "state", "pin")


def read_cases(path: Path) -> list[tuple[str, str]]:
    """(case id, address) pairs, in file order."""
    text = path.read_text(encoding="utf-8")
    if path.suffix == ".md":
        cases = re.findall(r"^## (\S+)[^\n]*\n.*?```text\n(.*?)\n```", text, flags=re.S | re.M)
        return [(case_id, address.strip()) for case_id, address in cases]
    return [(f"line-{i}", line.strip()) for i, line in enumerate(text.splitlines(), 1) if line.strip()]


def cleaned(fields: dict) -> str:
    """The normaliser's fields on one line; landmarks as 'relation anchor'."""
    out = []
    for key in FIELDS:
        value = fields.get(key)
        if key == "landmarks":
            value = "; ".join(f"{lm.get('relation') or ''} {lm.get('anchor') or ''}".strip() for lm in value or []) or None
        out.append(f"{key} `{value}`" if value else f"{key} –")
    return " · ".join(out)


def markdown(rows: list[dict], a: argparse.Namespace) -> str:
    lines = [f"# Model output on {a.input.name}", "",
             f"Generated by `scripts/parse_examples.py` on {date.today().isoformat()} with the model `{a.model}` "
             f"(run `{a.run_id}`; raw output in `{a.results_dir}/{a.run_id}.outputs.jsonl`). These addresses have no gold "
             "tags, so nothing here is scored. Do not edit by hand: run the script again.", "",
             "| Case | PIN check | Fields tagged |", "|---|---|---|"]
    for r in rows:
        labels = Counter(label for _, label in r["parts"])
        found = ", ".join(f"{label} ×{n}" if n > 1 else label for label, n in labels.items()) or "none"
        lines.append(f"| {r['id']} | {r['json'].get('pin_check', '–')} | {found} |")
    for r in rows:
        parts = " · ".join(f"{label} `{piece}`" for piece, label in r["parts"]) or "none"
        notes = " ".join(r["notes"]) or "The PIN is in the directory and nothing contradicts it."
        lines += ["", f"## {r['id']}", "", "```text", r["text"], "```", "", f"- **Parts tagged:** {parts}",
                  f"- **PIN check:** `{r['json'].get('pin_check', '–')}`. {notes}", f"- **Cleaned:** {cleaned(r['json'])}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("input", type=Path, help="a markdown file of cases, or a text file with one address per line")
    p.add_argument("--model", default="models/muril-synfull-s42")
    p.add_argument("--run-id", required=True)
    p.add_argument("--results-dir", type=Path, default=Path("results"))
    p.add_argument("--out-md", type=Path, default=None, help="also write a readable markdown file here")
    a = p.parse_args()
    cases = read_cases(a.input)
    if not cases:
        raise SystemExit(f"no addresses found in {a.input}")
    gaz = Gazetteer.load()
    if a.model in ("crf", "rules"):
        tagger = {"crf": crf_tagger, "rules": rules_tagger}[a.model](gaz)
    else:
        tagger = transformer_tagger(a.model)
    rows = []
    for case_id, address in cases:
        out = parse(address, tagger, gaz)
        rows.append({"id": case_id, "text": address, "model": a.model,
                     "parts": [[piece, label] for piece, label in out["spans"] if label],
                     "json": out["json"], "notes": out["notes"]})
    out_path = a.results_dir / f"{a.run_id}.outputs.jsonl"
    out_path.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    if a.out_md:
        a.out_md.write_text(markdown(rows, a), encoding="utf-8")
    checks = Counter(r["json"].get("pin_check") for r in rows)
    print(f"{a.run_id}: {len(rows)} addresses from {a.input}; pin_check {dict(checks)}; wrote {out_path}"
          + (f" and {a.out_md}" if a.out_md else ""))


if __name__ == "__main__":
    main()
